-- ProjectGG Game Tables Migration
-- Run this in Supabase SQL editor or use it to set up the database schema

-- Character collections (item slots for characters)
-- Note: ownership is enforced via the character_id foreign key to game_characters
-- which has user_id column with RLS
create table character_collections (
  id bigint generated by default as identity primary key,
  character_id uuid references game_characters(id) not null,
  item_name text,
  acquired_at timestamp with time zone default now()
);

-- Cloud saves for game characters
create table game_saves (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  character_id uuid not null,
  save_data jsonb not null,
  updated_at timestamp with time zone default now(),
  unique(user_id, character_id)
);

-- Game characters (mugshots, profiles, etc.)
create table game_characters (
  id uuid generated by default as identity primary key,
  user_id uuid references auth.users not null,
  name text not null,
  class text,
  level integer default 1,
  experience bigint default 0,
  mugshot_url text,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now(),
  unique(user_id, name)
);

-- Card collections (game-specific cards)
create table card_collections (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  game_code text not null,
  card_id text not null,
  rarity text,
  acquired_at timestamp with time zone default now(),
  unique(user_id, card_id)
);

-- Game trades
create table game_trades (
  id bigint generated by default as identity primary key,
  proposer_id uuid references auth.users not null,
  receiver_id uuid references auth.users not null,
  proposer_cards jsonb,
  receiver_cards jsonb,
  status text default 'pending',
  message text,
  created_at timestamp with time zone default now()
);

-- Incoming voice call notifications (for cross-platform calls: game <-> web)
create table incoming_voice_calls (
  id bigint generated by default as identity primary key,
  recipient_id uuid references auth.users not null,
  from_user_id uuid references auth.users not null,
  from_username text,
  guild_id text,
  channel_id text,
  created_at timestamp with time zone default now(),
  expires_at timestamp with time zone not null
);

-- Indexes for performance
create index idx_game_saves_user on game_saves(user_id);
create index idx_game_characters_user on game_characters(user_id);
create index idx_character_collections_character on character_collections(character_id);
create index idx_card_collections_user on card_collections(user_id);
create index idx_game_trades_proposer on game_trades(proposer_id);
create index idx_game_trades_receiver on game_trades(receiver_id);

-- Enable RLS (Row Level Security)
alter table game_saves enable row level security;
alter table game_characters enable row level security;
alter table character_collections enable row level security;
alter table card_collections enable row level security;
alter table game_trades enable row level security;

-- RLS Policies for game_saves
create policy "Users can view their own saves" on game_saves
  for select using (auth.uid() = user_id);

create policy "Users can insert their own saves" on game_saves
  for insert with check (auth.uid() = user_id);

create policy "Users can update their own saves" on game_saves
  for update using (auth.uid() = user_id);

-- RLS Policies for game_characters
create policy "Users can view their own characters" on game_characters
  for select using (auth.uid() = user_id);

create policy "Users can insert their own characters" on game_characters
  for insert with check (auth.uid() = user_id);

create policy "Users can update their own characters" on game_characters
  for update using (auth.uid() = user_id);

create policy "Users can delete their own characters" on game_characters
  for delete using (auth.uid() = user_id);

-- RLS Policies for card_collections
create policy "Users can view their own cards" on card_collections
  for select using (auth.uid() = user_id);

create policy "Users can insert their own cards" on card_collections
  for insert with check (auth.uid() = user_id);

-- RLS Policies for game_trades
create policy "Users can view trades they're involved in" on game_trades
  for select using (auth.uid() = proposer_id or auth.uid() = receiver_id);

create policy "Users can create trades as proposer" on game_trades
  for insert with check (auth.uid() = proposer_id);

create policy "Users can update trades they're involved in" on game_trades
  for update using (auth.uid() = proposer_id or auth.uid() = receiver_id);