-- RLS Policies for game_characters
create policy "Users can view their own characters" on projectgg.game_characters
  for select using (auth.uid() = user_id);
create policy "Users can insert their own characters" on projectgg.game_characters
  for insert with check (auth.uid() = user_id);
create policy "Users can update their own characters" on projectgg.game_characters
  for update using (auth.uid() = user_id);
create policy "Users can delete their own characters" on projectgg.game_characters
  for delete using (auth.uid() = user_id);

-- RLS Policies for game_saves
create policy "Users can view their own saves" on projectgg.game_saves
  for select using (auth.uid() = user_id);
create policy "Users can insert their own saves" on projectgg.game_saves
  for insert with check (auth.uid() = user_id);
create policy "Users can update their own saves" on projectgg.game_saves
  for update using (auth.uid() = user_id);

-- RLS Policies for character_collections (access through character or direct user_id)
create policy "Users can view their character collections" on projectgg.character_collections
  for select using (
    auth.uid() = user_id or 
    exists (
      select 1 from projectgg.game_characters gc
      where gc.id = projectgg.character_collections.character_id
      and gc.user_id = auth.uid()
    )
  );
create policy "Users can insert their own collections" on projectgg.character_collections
  for insert with check (
    auth.uid() = user_id or
    exists (
      select 1 from projectgg.game_characters gc
      where gc.id = projectgg.character_collections.character_id
      and gc.user_id = auth.uid()
    )
  );

-- RLS Policies for card_collections
create policy "Users can view their own cards" on projectgg.card_collections
  for select using (auth.uid() = user_id);
create policy "Users can insert their own cards" on projectgg.card_collections
  for insert with check (auth.uid() = user_id);

-- RLS Policies for game_trades
create policy "Users can view trades they're involved in" on projectgg.game_trades
  for select using (auth.uid() = proposer_id or auth.uid() = receiver_id);
create policy "Users can create trades as proposer" on projectgg.game_trades
  for insert with check (auth.uid() = proposer_id);
create policy "Users can update trades they're involved in" on projectgg.game_trades
  for update using (auth.uid() = proposer_id or auth.uid() = receiver_id);

-- RLS Policies for incoming_voice_calls
