  for select using (auth.uid() = recipient_id);
create policy "Users can insert calls" on projectgg.incoming_voice_calls
  for insert with check (auth.uid() = from_user_id);
create policy "Users can delete their consumed calls" on projectgg.incoming_voice_calls
  for delete using (auth.uid() = recipient_id);

-- RLS Policies for users status
create policy "Users can view their own status" on projectgg.users
  for select using (auth.uid() = user_id);
create policy "Users can update their own status" on projectgg.users
  for update using (auth.uid() = user_id);

