-- ProjectGG Game Tables - Complete Migration
-- Drops and recreates all game tables in projectgg schema
-- Run this in Supabase SQL editor (in the projectgg schema context)

-- Drop and recreate the entire schema for clean setup
drop schema if exists projectgg cascade;
create schema projectgg;

-- 1. Game characters (Parent table with UUID primary key)
create table projectgg.game_characters (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users not null,
  name text not null,
  class text,
  level integer default 1,
  experience bigint default 0,
  mugshot_url text,
  created_at timestamp with time zone default now(),
  updated_at timestamp with time zone default now(),
  unique(user_id, name)
);

-- 2. Character collections (item slots for characters)
create table projectgg.character_collections (
  id bigint generated by default as identity primary key,
  character_id uuid references projectgg.game_characters(id) not null,
  item_id uuid,
  item_name text,
  acquired_at timestamp with time zone default now(),
  user_id uuid references auth.users
);

-- 3. Cloud saves for game characters
create table projectgg.game_saves (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  character_id uuid not null,
  save_data jsonb not null,
  updated_at timestamp with time zone default now(),
  unique(user_id, character_id)
);

-- 4. Card collections (game-specific cards)
create table projectgg.card_collections (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  game_code text not null,
  card_id text not null,
  rarity text,
  acquired_at timestamp with time zone default now(),
  unique(user_id, card_id)
);

-- 5. Game trades
create table projectgg.game_trades (
  id bigint generated by default as identity primary key,
  proposer_id uuid references auth.users not null,
  receiver_id uuid references auth.users not null,
  proposer_cards jsonb,
  receiver_cards jsonb,
  status text default 'pending',
  message text,
  created_at timestamp with time zone default now()
);

-- 6. Incoming voice call notifications (for cross-platform calls: game <-> web)
create table projectgg.incoming_voice_calls (
  id bigint generated by default as identity primary key,
  recipient_id uuid references auth.users not null,
  from_user_id uuid references auth.users not null,
  from_username text,
  guild_id text,
  channel_id text,
  created_at timestamp with time zone default now(),
  expires_at timestamp with time zone not null
);

-- 7. User status for ProjectGG
create table projectgg.users (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users not null,
  status text default 'online',
  updated_at timestamp with time zone default now(),
  unique(user_id)
);

-- 8. Rank definitions (competitive ranks with 5 levels each for VOID and ASC)
create table projectgg.ranks (
  id text primary key,
  name text not null,
  code text not null,
  min_xp bigint not null,
  max_xp bigint not null default 2147483647,
  sort_order integer not null,
  description text
);

-- 9. Daily XP claims
create table projectgg.daily_xp_claims (
  user_id uuid references auth.users not null,
  claimed_at timestamp with time zone default now(),
  primary key (user_id, date_trunc('day', claimed_at))
);

-- 10. Games master (reference table for all games)
create table projectgg.games_master (
  id bigint generated by default as identity primary key,
  code text unique not null,
  name text not null,
  desc text,
  sequence_timeline integer,
  sequence_release integer,
  is_series boolean default false,
  series_name text,
  genres text[],
  cover_url text,
  external_id text,
  rating numeric,
  tier text,
  platforms text[] default ARRAY['pc'],
  sources text[] default ARRAY['pc'],
  last_synced_at timestamp with time zone default now(),
  broken_fields text[],
  locked_columns text[]
);

-- Indexes for performance
create index idx_game_saves_user on projectgg.game_saves(user_id);
create index idx_game_saves_character on projectgg.game_saves(character_id);
create index idx_game_characters_user on projectgg.game_characters(user_id);
create index idx_card_collections_user on projectgg.card_collections(user_id);
create index idx_game_trades_proposer on projectgg.game_trades(proposer_id);
create index idx_game_trades_receiver on projectgg.game_trades(receiver_id);
create index idx_incoming_voice_calls_recipient on projectgg.incoming_voice_calls(recipient_id);
create index idx_ranks_sort_order on projectgg.ranks(sort_order);
create index idx_games_master_code on projectgg.games_master(code);
create index idx_games_master_series on projectgg.games_master(series_name);

